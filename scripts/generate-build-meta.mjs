import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const releaseSha = String(process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || 'development').trim()
const releaseBranch = String(process.env.WORKERS_CI_BRANCH || process.env.GITHUB_REF_NAME || 'development').trim()
const source = `// Generated by scripts/generate-build-meta.mjs. Do not edit during a build.\nexport const HIVE_UI_BUILD_SHA = ${JSON.stringify(releaseSha)}\nexport const HIVE_UI_BUILD_BRANCH = ${JSON.stringify(releaseBranch)}\n`
await writeFile(resolve(root, 'workers/gateway/build-meta.ts'), source)
